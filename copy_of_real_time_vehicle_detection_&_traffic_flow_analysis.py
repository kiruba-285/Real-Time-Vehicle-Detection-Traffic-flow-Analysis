import numpy as np
import pandas as pd
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense, Dropout
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, r2_score

# Load dataset
data = pd.read_csv('/content/traffic_analysis (17).csv')


data.columns = [col.strip().lower() for col in data.columns]

required_columns = {'cars', 'buses'}
if not required_columns.issubset(data.columns):
    raise KeyError(f"Missing columns in dataset: {required_columns - set(data.columns)}")

# Preprocess data
scaler = MinMaxScaler()
data_scaled = scaler.fit_transform(data[['cars', 'buses']])

def create_sequences(data, time_steps=20):
    X, y = [], []
    for i in range(len(data) - time_steps):
        X.append(data[i:i+time_steps])
        y.append(data[i+time_steps])
    return np.array(X), np.array(y)

X, y = create_sequences(data_scaled)
train_size = int(len(X) * 0.8)
X_train, X_test = X[:train_size], X[train_size:]
y_train, y_test = y[:train_size], y[train_size:]

# Build model
model = Sequential([
    LSTM(128, return_sequences=True, input_shape=(20, 2)),
    Dropout(0.3),
    LSTM(64, return_sequences=True),
    Dropout(0.3),
    LSTM(32, return_sequences=False),
    Dropout(0.3),
    Dense(2)
])

model.compile(optimizer='adam', loss='mse')

# Train model
history = model.fit(X_train, y_train, epochs=50, batch_size=16, validation_data=(X_test, y_test), verbose=1)

