from tensorflow.keras.callbacks import EarlyStopping
from tensorflow.keras.optimizers import Adam
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, r2_score

data = pd.read_csv('/content/traffic_analysis (17).csv')

data.columns = [col.strip().lower() for col in data.columns]
required_columns = {'cars', 'buses'}
if not required_columns.issubset(data.columns):
    raise KeyError(f"Missing columns in dataset: {required_columns - set(data.columns)}")

scaler = MinMaxScaler()
data_scaled = scaler.fit_transform(data[['cars', 'buses']])


def create_sequences(data, time_steps=20):
    X, y = [], []
    for i in range(len(data) - time_steps):
        X.append(data[i:i+time_steps])
        y.append(data[i+time_steps])
    return np.array(X), np.array(y)

X, y = create_sequences(data_scaled)
train_size = int(len(X) * 0.8)
X_train, X_test = X[:train_size], X[train_size:]
y_train, y_test = y[:train_size], y[train_size:]


X_train = X_train.reshape(X_train.shape[0], X_train.shape[1], 2)
X_test = X_test.reshape(X_test.shape[0], X_test.shape[1], 2)


model = Sequential([
    Bidirectional(LSTM(128, return_sequences=True, input_shape=(20, 2))),
    BatchNormalization(),
    Dropout(0.2),
    Bidirectional(LSTM(64, return_sequences=False)),
    BatchNormalization(),
    Dropout(0.2),
    Dense(2)
])

optimizer = Adam(learning_rate=0.001)
model.compile(optimizer=optimizer, loss='mae')

early_stopping = EarlyStopping(monitor='val_loss', patience=3, restore_best_weights=True)


history = model.fit(X_train, y_train, epochs=20, batch_size=32, validation_data=(X_test, y_test), verbose=1, callbacks=[early_stopping])


y_pred = model.predict(X_test)
y_test_rescaled = scaler.inverse_transform(y_test)
